fn live_mcp_run_status_and_verify_execute_the_shared_command_bus() {
    let repo = live_repo();
    let service: Arc<dyn QualityService> = Arc::new(LiveService::new(&repo.0));
    let run = protocol_call(
        &service,
        "quality_run",
        &serde_json::json!({"change": "live", "scope": "all", "evidence_policy": "standard"}),
    );
    assert!(run.contains("\"executed\":true"), "{run}");
    assert!(run.contains("\"outcome\":\"passed\""), "{run}");

    let status = protocol_call(&service, "quality_status", &serde_json::json!({}));
    assert!(status.contains("\"outcome\":\"passed\""), "{status}");

    let verify = protocol_call(
        &service,
        "quality_verify",
        &serde_json::json!({"change": "live"}),
    );
    assert!(verify.contains("PROVEN"), "{verify}");
}
