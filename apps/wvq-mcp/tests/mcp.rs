fn git(root: &Path, args: &[&str]) {
    let output = ProcessCommand::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn protocol_call(
    service: &Arc<dyn QualityService>,
    name: &str,
    arguments: &serde_json::Value,
) -> String {
    protocol_call_server(quality_server(service), name, arguments)
}

fn protocol_call_server(
    server: mcport::ConcurrentMcpServer,
    name: &str,
    arguments: &serde_json::Value,
) -> String {
    let request = serde_json::json!({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "tools/call",
        "params": {"name": name, "arguments": arguments}
    });
    let input = Cursor::new(format!("{request}\n").into_bytes());
    let writer = SharedWriter::default();
    let captured = writer.clone();
    serve_controlled_streams(Arc::new(server), input, writer, runtime_config()).unwrap();
    let bytes = captured.0.lock().unwrap().clone();
    String::from_utf8(bytes).unwrap()
}

#[test]
fn authoring_profile_exposes_only_five_high_level_playwright_tools() {
    let service: Arc<dyn QualityService> = Arc::new(FakeService::default());
    let built = authoring_server(&service, "live", "HEAD", "WORKTREE");
    let catalog = built.catalog();
    let names = catalog
        .as_array()
        .unwrap()
        .iter()
        .map(|tool| tool["name"].as_str().unwrap())
        .collect::<Vec<_>>();
    assert_eq!(
        names,
        [
            "quality_test_draft",
            "quality_test_validate",
            "quality_test_preview",
            "quality_test_promote",
            "quality_test_heal"
        ]
    );
    assert!(built.schema_defects().is_empty());
    for banned in [
        "browser_click",
        "browser_navigate",
        "javascript_eval",
        "shell",
    ] {
        assert!(!names.contains(&banned));
    }
}

#[test]
fn host_selects_the_authoring_profile_and_fixed_revision_range() {
    let options = parse_host_args(&[
        "--profile".into(),
        "authoring".into(),
        "--change".into(),
        "live".into(),
        "--base".into(),
        "origin/main".into(),
        "--head".into(),
        "WORKTREE".into(),
    ])
    .unwrap();
    assert_eq!(options.profile, HostProfile::Authoring);
    assert_eq!(options.change, "live");
    assert_eq!(options.base, "origin/main");
    assert_eq!(options.head, "WORKTREE");
}

#[test]
fn authoring_profile_runs_the_shared_command_bus_with_fixed_scope() {
    let service: Arc<dyn QualityService> = Arc::new(FakeService::default());
    let draft = protocol_call_server(
        authoring_server(&service, "live", "BASE", "HEAD"),
        "quality_test_draft",
        &serde_json::json!({"token_budget": 8000}),
    );
    assert!(draft.contains("\"change\":\"live\""), "{draft}");
    assert!(draft.contains("\"base\":\"BASE\""), "{draft}");
    assert!(draft.contains("\"candidate\":null"), "{draft}");

    let validated = protocol_call_server(
        authoring_server(&service, "live", "BASE", "HEAD"),
        "quality_test_validate",
        &serde_json::json!({"program": {"id": "generated-program"}}),
    );
    assert!(validated.contains("\"valid\":true"), "{validated}");
    assert!(validated.contains("\"persisted\":false"), "{validated}");

    let promoted = protocol_call_server(
        authoring_server(&service, "live", "BASE", "HEAD"),
        "quality_test_promote",
        &serde_json::json!({
            "preview_id": "preview-generated-program",
            "program": {"id": "generated-program"}
        }),
    );
    assert!(promoted.contains("\"program_revision\":1"), "{promoted}");
    assert!(promoted.contains("\"persisted\":true"), "{promoted}");

    let healed = protocol_call_server(
        authoring_server(&service, "live", "BASE", "HEAD"),
        "quality_test_heal",
        &serde_json::json!({
            "program_id": "generated-program",
            "expected_program_revision": 1,
            "edits": [{
                "edit": "insert_wait",
                "after": 0,
                "condition": {"kind": "url", "route": "/ready"}
            }]
        }),
    );
    assert!(healed.contains("\"program_revision\":2"), "{healed}");
    assert!(healed.contains("\"persisted\":true"), "{healed}");
}

#[test]
fn default_profile_exposes_exactly_seven_tools() {
    let catalog = server().catalog();
    let tools = catalog.as_array().expect("tool catalog is an array");
    let names: Vec<&str> = tools
        .iter()
        .map(|tool| {
            tool.get("name")
                .and_then(mcport::Value::as_str)
                .unwrap_or("")
        })
        .collect();
    assert_eq!(names, DEFAULT_TOOLS);
    for banned in [
        "quality_select",
        "quality_explore",
        "quality_mutate",
        "quality_replay",
        "browser_click",
        "shell",
    ] {
        assert!(
            !names.contains(&banned),
            "default profile must not expose {banned}"
        );
    }
}

