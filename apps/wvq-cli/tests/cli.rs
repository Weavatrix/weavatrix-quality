#[test]
fn live_cli_run_status_and_verify_share_persistent_evidence() {
    let repo = live_repo();
    let root = repo.0.to_str().unwrap();
    let run = wvq_cli::run(&argv(&[
        "--repo", root, "run", "--change", "live", "--scope", "all",
    ]));
    assert_eq!(run.code, 0, "{}", run.stderr);
    assert!(run.stdout.contains("\"executed\": true"));
    assert!(run.stdout.contains("\"outcome\": \"passed\""));

    let status = wvq_cli::run(&argv(&["--repo", root, "status"]));
    assert_eq!(status.code, 0, "{}", status.stderr);
    assert!(status.stdout.contains("\"outcome\": \"passed\""));

    let verify = wvq_cli::run(&argv(&["--repo", root, "verify", "--change", "live"]));
    assert_eq!(verify.code, 0, "{}", verify.stderr);
    assert!(verify.stdout.contains("PROVEN"));
}

#[test]
fn analyze_debt_select_run_verify_explain_are_wired() {
    let fake = FakeService::default();
    fake.set_verdict("UNPROVEN");
    fake.put_explain(wvq_command_bus::ExplainReply {
        id: "others-visible".into(),
        kind: "obligation".into(),
        summary: "others stay visible".into(),
        provenance: vec!["quality.yaml:1".into()],
    });
    for cmd in ["analyze", "debt", "select", "run", "verify"] {
        let output = run_with(&argv(&[cmd, "--change", "sankey-others"]), &fake);
        assert_ne!(
            output.code, 2,
            "{cmd} must not be a usage error: {}",
            output.stderr
        );
        assert!(
            output.stderr.is_empty() || output.code != 0,
            "{cmd}: {}",
            output.stderr
        );
    }
    let explained = run_with(&argv(&["explain", "others-visible"]), &fake);
    assert_eq!(explained.code, 0, "{}", explained.stderr);
    assert!(explained.stdout.contains("others stay visible"));

    let model = run_with(
        &argv(&[
            "model",
            "--change",
            "sankey-others",
            "--kind",
            "runtime",
            "--prompt",
            "classify this failure",
        ]),
        &fake,
    );
    assert_eq!(model.code, 0, "{}", model.stderr);
    assert!(model.stdout.contains("fake-local-model"));
}

