#[test]
fn misspelled_or_duplicate_flags_are_rejected() {
    let fake = FakeService::default();
    let misspelled = run_with(&argv(&["run", "--scop", "all"]), &fake);
    assert_ne!(misspelled.code, 0);
    assert!(misspelled.stderr.contains("unknown flag --scop"));

    let duplicate = run_with(
        &argv(&["verify", "--change", "one", "--change", "two"]),
        &fake,
    );
    assert_ne!(duplicate.code, 0);
    assert!(duplicate.stderr.contains("more than once"));
}

