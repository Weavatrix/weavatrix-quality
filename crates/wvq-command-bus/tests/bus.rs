#[test]
fn live_model_call_charges_persistent_per_change_budget() {
    let repo = live_runner_repo();
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let address = listener.local_addr().unwrap();
    std::fs::write(
        repo.0.join(".weavatrix-quality/config.yaml"),
        format!(
            "quality_policy_v: 1\n\ntest_bindings:\n  - path: tests/addition.rs\n    obligations: [addition-suite]\n    cost: 10\n    flake_penalty: 0\n\nai:\n  endpoint: http://{address}/v1/chat/completions\n  model: local-test\n  max_output_tokens: 8\n  max_tokens_per_change: 15\n  max_runtime_tokens: 100\n  max_browser_escape_calls: 1\n  max_vision_calls: 1\n  max_cost_micros: 100\n  input_micros_per_million: 1000000\n  output_micros_per_million: 2000000\n"
        ),
    )
    .unwrap();
    let server = thread::spawn(move || {
        let (mut stream, _) = listener.accept().unwrap();
        let request = read_http_request(&mut stream);
        assert!(
            String::from_utf8_lossy(&request).starts_with("POST /v1/chat/completions HTTP/1.1")
        );
        let body = br#"{"model":"local-test","choices":[{"message":{"content":"inspect boundary"}}],"usage":{"prompt_tokens":3,"completion_tokens":2}}"#;
        write!(
            stream,
            "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            body.len()
        )
        .unwrap();
        stream.write_all(body).unwrap();
    });
    let first = LiveService::new(&repo.0)
        .model(&ModelCommand {
            change: "live-add".into(),
            kind: "planning".into(),
            prompt: "probe".into(),
        })
        .unwrap();
    server.join().unwrap();
    assert_eq!(first.text, "inspect boundary");
    assert_eq!(first.input_tokens + first.output_tokens, 5);
    assert_eq!(first.cost_micros, 7);

    let error = LiveService::new(&repo.0)
        .model(&ModelCommand {
            change: "live-add".into(),
            kind: "planning".into(),
            prompt: "second probe".into(),
        })
        .unwrap_err();
    assert!(matches!(error, BusError::Model(_)));
    assert!(error.to_string().contains("AI_BUDGET_EXHAUSTED"));
}

