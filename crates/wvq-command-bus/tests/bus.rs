#[test]
#[allow(clippy::too_many_lines)]
fn live_run_executes_persists_and_proves_a_real_registered_suite() {
    let repo = live_runner_repo();
    std::fs::write(
        repo.0.join("src/lib.rs"),
        "/// Add two integers.\npub fn add(a: i32, b: i32) -> i32 { a + b }\n",
    )
    .unwrap();
    let service = LiveService::new(&repo.0);
    let reply = service
        .run(&RunCommand {
            change: "live-add".into(),
            scope: "impacted".into(),
            evidence_policy: "standard".into(),
            base: "HEAD".into(),
            head: "WORKTREE".into(),
        })
        .unwrap();
    assert!(reply.executed);
    assert_eq!(reply.outcome, "passed");
    assert_eq!(reply.requested_scope, "impacted");
    assert_eq!(reply.scope, "all", "incomplete selection must widen safely");
    assert!(
        reply
            .artifact_handles
            .iter()
            .any(|handle| handle.ends_with("-summary"))
    );
    assert!(
        reply
            .artifact_handles
            .iter()
            .any(|handle| handle.ends_with("-graph-diff"))
    );
    assert!(
        reply
            .artifact_handles
            .iter()
            .any(|handle| handle.ends_with("-impact"))
    );

    let reopened = LiveService::new(&repo.0);
    let status = reopened
        .status(&wvq_command_bus::StatusCommand {
            run_id: Some(reply.run_id.clone()),
        })
        .unwrap();
    assert_eq!(status.outcome.as_deref(), Some("passed"));
    assert_eq!(status.handles, reply.artifact_handles);

    let summary = reopened
        .evidence(&EvidenceCommand {
            handle: reply
                .artifact_handles
                .iter()
                .find(|handle| handle.ends_with("-summary"))
                .unwrap()
                .clone(),
        })
        .unwrap();
    assert_eq!(summary.kind, "execution-summary");
    assert!(
        summary
            .inline_text
            .as_deref()
            .unwrap()
            .contains("cargo-test")
    );

    let impact = reopened
        .evidence(&EvidenceCommand {
            handle: reply
                .artifact_handles
                .iter()
                .find(|handle| handle.ends_with("-impact"))
                .unwrap()
                .clone(),
        })
        .unwrap();
    assert_eq!(impact.kind, "impacted-surface");
    assert!(impact.inline_text.is_some());

    let verified = reopened
        .verify(&VerifyCommand {
            change: "live-add".into(),
        })
        .unwrap();
    assert_eq!(verified.verdict, "PROVEN");
    assert_eq!(verified.exit_code(), 0);

    let planned = reopened
        .plan(&PlanCommand {
            change: "live-add".into(),
        })
        .unwrap();
    assert_eq!(planned.existing_proofs.len(), 1);
    assert!(planned.gaps.is_empty(), "{:?}", planned.gaps);
    let proof = reopened
        .explain(&ExplainCommand {
            id: planned.existing_proofs[0].clone(),
        })
        .unwrap();
    assert_eq!(proof.kind, "proof");
    assert!(
        proof
            .provenance
            .iter()
            .any(|item| item.starts_with("revision "))
    );

    let run = reopened
        .explain(&ExplainCommand {
            id: reply.run_id.clone(),
        })
        .unwrap();
    assert_eq!(run.kind, "run");
    assert!(run.summary.contains("passed"));

    let selection = reopened
        .explain(&ExplainCommand {
            id: "tests/addition.rs".into(),
        })
        .unwrap();
    assert_eq!(selection.kind, "selection");
    assert!(!selection.provenance.is_empty());
}

